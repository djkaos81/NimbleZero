#!/bin/sh
# Regenerate external/configs/*_defconfig from the fragments (later fragments win).
set -e
cd "$(dirname "$0")/../external/configs"
gen() { out=$1; shift; { echo "# GENERATED by scripts/gen-defconfigs.sh from: $*"; for f in "$@"; do cat "fragments/$f.frag"; done; } |
	awk -F= '/^#/ {next} NF {k=$1; if (!(k in seen)) order[++n]=k; seen[k]=$0} END {for (i=1;i<=n;i++) print seen[order[i]]}' > "$out"; }
gen nz_minimal_defconfig common minimal
gen nz_compat_defconfig common compat-libs compat-busybox
[ -f fragments/compat-systemd.frag ] && gen nz_compat_systemd_defconfig common compat-libs compat-systemd
echo "defconfigs regenerated"
